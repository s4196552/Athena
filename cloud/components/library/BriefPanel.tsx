'use client';

import { useState, useTransition } from 'react';
import { Icon } from '@/lib/icons';
import { summarise, type BriefResult } from '@/app/w/[ws]/summarise';
import s from './brief.module.css';

/* "Summarise this selection."
 *
 * Opt-in, on a button, rather than generated on every library page load. Two
 * reasons, and the second is the real one: a summary nobody asked for is a
 * model call nobody is paying attention to, and running one per page view on a
 * shared key is how a demo becomes an invoice.
 */
export function BriefPanel({ ws, query }: { ws: string; query: string }) {
  const [open, setOpen] = useState(false);
  const [brief, setBrief] = useState<BriefResult | null>(null);
  const [pending, start] = useTransition();

  function run() {
    setOpen(true);
    setBrief(null);
    start(async () => setBrief(await summarise(ws, query)));
  }

  return (
    <>
      <button type="button" className={s.trigger} onClick={run} disabled={pending}>
        <Icon name="auto_awesome" size={14} />
        {pending ? 'Reading…' : 'Summarise'}
      </button>

      {open && (
        <div className={s.sheet} role="dialog" aria-label="Summary of this selection">
          <header className={s.head}>
            <h2 className={s.title}>{brief?.title ?? 'Summarising…'}</h2>
            <button
              type="button"
              className={s.close}
              onClick={() => setOpen(false)}
              aria-label="Close summary"
            >
              <Icon name="close" size={17} />
            </button>
          </header>

          {!brief ? (
            <p className={s.waiting}>Counting the selection…</p>
          ) : (
            <>
              {brief.intro && <p className={s.intro}>{brief.intro}</p>}

              {(brief.themes?.length || brief.about?.length) && (
                <div className={s.chips}>
                  {brief.themes?.map((t) => (
                    <span key={`t-${t}`} className={s.theme}>
                      <Icon name="label" size={12} />{t}
                    </span>
                  ))}
                  {brief.about?.map((o) => (
                    <span key={`o-${o}`} className={s.about}>
                      <Icon name="bookmark" size={12} />{o}
                    </span>
                  ))}
                </div>
              )}

              {brief.intro && <hr className={s.rule} />}

              <Markdown text={brief.body} />

              {brief.note && <p className={s.note}>{brief.note}</p>}

              {/* Provenance on every brief, the way agent_finding.decided_by is
                  on every verdict: a summary whose source is visible is one a
                  person can weigh. */}
              <p className={s.by}>
                {brief.producedBy === 'counted'
                  ? 'Counted from the catalogue. No model was used.'
                  : `Counts from the catalogue; the opening paragraph written by ${brief.producedBy}. Every number above is arithmetic, not generated.`}
              </p>
            </>
          )}
        </div>
      )}
    </>
  );
}

/* A deliberately tiny markdown renderer.
 *
 * The brief is generated by compileBrief(), so the grammar is known and
 * closed: h3, bold-leading paragraphs, and "- " list items. Pulling in a
 * markdown library to render four constructs would add a parser -- and an
 * HTML sanitiser to go with it -- to handle input this file already controls.
 * Text is rendered as text; nothing here sets innerHTML.
 */
function Markdown({ text }: { text: string }) {
  const blocks: React.ReactNode[] = [];
  let list: string[] = [];

  const flush = (key: string) => {
    if (!list.length) return;
    blocks.push(
      <ul key={key} className={s.list}>
        {list.map((item, i) => {
          // compileBrief emits "Name — 42". Splitting on the em dash gives the
          // count its own element, which is what lets CSS right-align it into
          // a column without the brief having to be a table.
          const cut = item.lastIndexOf(' — ');
          if (cut === -1) return <li key={i}>{inline(item)}</li>;
          return (
            <li key={i}>
              <span>{inline(item.slice(0, cut))}</span>
              <span>{item.slice(cut + 3)}</span>
            </li>
          );
        })}
      </ul>,
    );
    list = [];
  };

  text.split('\n').forEach((raw, i) => {
    const lineText = raw.trim();
    if (!lineText) { flush(`l${i}`); return; }
    if (lineText.startsWith('### ')) {
      flush(`l${i}`);
      blocks.push(<h3 key={i} className={s.h3}>{lineText.slice(4)}</h3>);
      return;
    }
    if (lineText.startsWith('- ')) { list.push(lineText.slice(2)); return; }
    flush(`l${i}`);
    blocks.push(<p key={i} className={s.p}>{inline(lineText)}</p>);
  });
  flush('last');

  return <div className={s.body}>{blocks}</div>;
}

/** Only **bold**, which is all compileBrief emits. */
function inline(text: string): React.ReactNode {
  return text.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith('**') && part.endsWith('**')
      ? <strong key={i}>{part.slice(2, -2)}</strong>
      : <span key={i}>{part}</span>);
}
